/**
 * Write docs/commands.md from the program itself, or check it is current.
 *
 * The reference is generated because a hand written one goes stale in a week,
 * and a stale command reference is worse than none: the despatchers read it
 * rather than the help.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Command } from 'commander';
import { buildProgram } from '../src/cli/program';
import { recordingIo } from '../src/cli/output';

const target = join(__dirname, '..', 'docs', 'commands.md');

function optionLines(command: Command): string[] {
  return command.options.map((option) => `  - \`${option.flags}\` ${option.description}`);
}

function walk(command: Command, path: string[], lines: string[]): void {
  const name = [...path, command.name()].filter((part) => part !== '').join(' ');
  if (path.length > 0) {
    lines.push(`### \`${name}\``);
    lines.push('');
    lines.push(command.description());
    lines.push('');
    const options = optionLines(command);
    if (options.length > 0) {
      lines.push('Options:');
      lines.push(...options);
      lines.push('');
    }
  }
  for (const child of command.commands) {
    walk(
      child as Command,
      [...path, command.name()].filter((part) => part !== ''),
      lines,
    );
  }
}

function render(): string {
  const program = buildProgram(recordingIo());
  const lines: string[] = ['# keelroom commands', ''];
  lines.push('Generated by `npm run commands`. Do not edit by hand.');
  lines.push('');
  const global = program.options.map((option) => `- \`${option.flags}\` ${option.description}`);
  lines.push('## Options on every command', '', ...global, '');
  lines.push('## Commands', '');
  walk(program, [], lines);
  return `${lines.join('\n').trimEnd()}\n`;
}

function main(): void {
  const wanted = render();
  if (process.argv.includes('--check')) {
    const current = readFileSync(target, 'utf8');
    if (current !== wanted) {
      console.error('docs/commands.md is out of date, run npm run commands');
      process.exit(1);
    }
    console.log('the command reference is current');
    return;
  }
  writeFileSync(target, wanted);
  console.log(`wrote ${target}`);
}

main();
