/**
 * Write docs/rules.md from the rule ids in the source, or check it is current.
 *
 * Every finding this system raises carries a rule id, and the pilots and the
 * agents argue with the ids rather than with the code. So the handbook is
 * generated: an id that exists in the source and not in the handbook is a rule
 * nobody outside can look up, and an id in the handbook that no longer exists in
 * the source is a rule somebody is still being told about.
 */

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = join(__dirname, '..');
const target = join(root, 'docs', 'rules.md');

export interface Rule {
  readonly id: string;
  readonly message: string;
  readonly severity: string;
  readonly file: string;
}

const CALL = /\.(block|advise|note)\(\s*'([A-Z][A-Z0-9-]{3,})',\s*(?:'([^']+)'|([A-Za-z][\w.]*))/g;
const MAKE = /makeFinding\(\s*'([A-Z][A-Z0-9-]{3,})',\s*'(\w+)',\s*'([^']+)'/g;
const REASON = /'([A-Z]{2,8}(?:-[A-Z0-9]{1,6}){1,3})'/g;

function sources(dir: string, found: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      sources(full, found);
    } else if (entry.endsWith('.ts')) {
      found.push(full);
    }
  }
  return found;
}

export function collectRules(): Rule[] {
  const rules = new Map<string, Rule>();
  for (const file of sources(join(root, 'src'))) {
    const text = readFileSync(file, 'utf8');
    const where = relative(root, file);
    for (const match of text.matchAll(CALL)) {
      const [, severity, id, message, fromValue] = match;
      rules.set(id ?? '', {
        id: id ?? '',
        message: message ?? `the text of the ${fromValue ?? 'finding'} itself`,
        severity: severity === 'block' ? 'blocking' : severity === 'advise' ? 'advice' : 'note',
        file: where,
      });
    }
    for (const match of text.matchAll(MAKE)) {
      const [, id, severity, message] = match;
      if (!rules.has(id ?? '')) {
        rules.set(id ?? '', {
          id: id ?? '',
          message: message ?? '',
          severity: severity ?? 'note',
          file: where,
        });
      }
    }
    if (where.includes('ukc/policy') || where.includes('tariff/penalty')) {
      for (const match of text.matchAll(REASON)) {
        const id = match[1] ?? '';
        if (!rules.has(id)) {
          rules.set(id, { id, message: 'reason code', severity: 'note', file: where });
        }
      }
    }
  }
  return [...rules.values()].sort((a, b) => a.id.localeCompare(b.id));
}

function render(rules: readonly Rule[]): string {
  const lines = ['# keelroom rules', ''];
  lines.push('Generated by `npm run handbook`. Do not edit by hand.');
  lines.push('');
  lines.push('Every finding this system raises carries one of these ids.');
  lines.push('');
  lines.push('| rule | severity | what it means | where |');
  lines.push('| --- | --- | --- | --- |');
  for (const rule of rules) {
    lines.push(`| \`${rule.id}\` | ${rule.severity} | ${rule.message} | \`${rule.file}\` |`);
  }
  lines.push('');
  lines.push(`${rules.length} rules.`);
  return `${lines.join('\n')}\n`;
}

function main(): void {
  const wanted = render(collectRules());
  if (process.argv.includes('--check')) {
    const current = readFileSync(target, 'utf8');
    if (current !== wanted) {
      console.error('docs/rules.md is out of date, run npm run handbook');
      process.exit(1);
    }
    console.log('the handbook is current');
    return;
  }
  writeFileSync(target, wanted);
  console.log(`wrote ${target}`);
}

if (require.main === module) {
  main();
}
