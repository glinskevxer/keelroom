/**
 * Write docs/api.md from the router, or check it is current.
 *
 * The api is what the agents write against, so its documentation has to come
 * from the routes themselves rather than from somebody's memory of them. The
 * router is built against a district in memory purely to enumerate what it
 * serves; nothing is called.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { openMemory } from '../src/storage/database';
import { migrate } from '../src/storage/migrate';
import { createDistrict } from '../src/service/setup';
import { contextFrom } from '../src/service/context';
import { defaultConfig } from '../src/service/config';
import { buildRouter } from '../src/api/routes';

const root = join(__dirname, '..');
const target = join(root, 'docs', 'api.md');

/** What each route is for, in the district's own words. */
const NOTES: Record<string, string> = {
  '/': 'what this is and everything it serves',
  '/district': 'the reaches with both depths, and the berths',
  '/tides/:station': 'the height now and the turns of the tide, `days` ahead',
  '/vessels': 'every ship on the books with her units, paged by `limit` and `offset`',
  '/vessels/:imo': 'one ship in full',
  '/movements': 'what is expected, `days` ahead, counted by state and paged',
  '/movements/:reference': 'one movement and the times off the card',
  '/movements/:reference/plan': 'the windows for it, `hours` either side',
  '/agents/:agent/movements': 'everything that agent has ordered, paged',
  '/agents/:agent/statement': 'what they owe, aged, and what is under dispute',
  '/board': 'the turn board in order',
  '/notices': 'what is in force and what is standing',
  '/traffic': 'who is in which reach and where they meet',
  '/berths': 'who is lying where, and the utilisation',
  '/weather': 'the log, and the reading a plan would use',
  '/tugs': 'the fleet and what is booked against it',
  '/return': 'the district return for the last `days`',
  '/windows': 'the tide either side of a window',
};

export function routes(): { method: string; path: string }[] {
  const db = openMemory();
  migrate(db);
  createDistrict(db, JSON.parse(readFileSync(join(root, 'docs', 'example-district.json'), 'utf8')));
  const context = contextFrom(db, { ...defaultConfig('KLR'), databasePath: ':memory:' });
  const listed = buildRouter(context).list();
  db.close();
  return listed;
}

function render(): string {
  const lines = ['# keelroom api', ''];
  lines.push('Generated by `npm run api-docs`. Do not edit by hand.');
  lines.push('');
  lines.push('The api is read only. Everything answers json, nothing is cached, and a handler');
  lines.push('that refuses answers 400 for a bad request, 404 for something that is not there,');
  lines.push('405 for the wrong method and 500 for anything else.');
  lines.push('');
  lines.push('A paged route answers `{ items, total, limit, offset, next }`. Ask for the next');
  lines.push('page with the `next` it gave you; when there is no `next` there is no more.');
  lines.push('');
  lines.push('| method | path | what it answers |');
  lines.push('| --- | --- | --- |');
  for (const route of routes()) {
    lines.push(`| ${route.method} | \`${route.path}\` | ${NOTES[route.path] ?? ''} |`);
  }
  lines.push('');
  lines.push('Start it with `keelroom serve --port 8080`.');
  return `${lines.join('\n')}\n`;
}

function main(): void {
  const wanted = render();
  if (process.argv.includes('--check')) {
    const current = readFileSync(target, 'utf8');
    if (current !== wanted) {
      console.error('docs/api.md is out of date, run npm run api-docs');
      process.exit(1);
    }
    console.log('the api reference is current');
    return;
  }
  writeFileSync(target, wanted);
  console.log(`wrote ${target}`);
}

if (require.main === module) {
  main();
}
